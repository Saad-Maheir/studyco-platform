export function getFeatureText(featureStr, lang = 'ar') {
  if (!featureStr) return '';
  const item = LC_FEATURES[featureStr.trim()];
  if (item && item[lang]) return item[lang];
  return featureStr;
}

export function getLcText(key, lang = 'ar', i18nInstance = null) {
  if (i18nInstance && typeof i18nInstance.t === 'function') {
    const val = i18nInstance.t(key);
    if (val && val !== key) return val;
  }
  const dict = LC_UI_FALLBACKS[lang] || LC_UI_FALLBACKS.en;
  return dict[key] || LC_UI_FALLBACKS.en[key] || key;
}

